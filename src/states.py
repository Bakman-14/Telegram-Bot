"""
FSM стани для діалогового потоку створення нагадування.

Цей модуль визначає всі етапи (State) для машини станів (FSM),
які використовуються aiogram для спілкування з користувачем
під час створення або редагування нагадування.
"""

from aiogram.fsm.state import State, StatesGroup


class ReminderStates(StatesGroup):
    """Стани FSM для процесу створення нагадування.
    
    Послідовність діалогу:
    1. text — запрошення на введення тексту нагадування
    2. due — запрошення на введення дати/часу
    3. recurrence — запрошення: чи повторюється щодня?
    4. interval — запрошення на введення інтервалу (кожні N днів)
    5. recurrence_end — запрошення на введення дати закінчення повторень
    """
    
    text = State()
    """Стан очікування тексту нагадування від користувача"""
    
    due = State()
    """Стан очікування дати/часу нагадування (напр. '2026-07-15 10:30')"""
    
    recurrence = State()
    """Стан очікування вибору: повторюється щодня чи ні?"""
    
    interval = State()
    """Стан очікування числа — інтервалу повторення (кожні N днів)"""
    
    recurrence_end = State()
    """Стан очікування дати закінчення повторень (опціонально)"""
