"""
Централізована конфігурація для телеграм-бота.

Цей модуль містить всі константи, параметри та налаштування,
які використовуються по всьому боту.
"""

import logging
import os
from pathlib import Path

from dotenv import load_dotenv

# ============================================================================
# БАЗОВІ ШЛЯХИ
# ============================================================================
# SRC_DIR — директорія папки з кодом (де лежить цей config.py)
SRC_DIR = Path(__file__).resolve().parent

# BASE_DIR — корінь проєкту (піднімаємося на один рівень вгору з папки src)
BASE_DIR = SRC_DIR.parent

# DB_PATH — шлях до бази даних SQLite
DB_PATH = SRC_DIR / "reminders.db"

# ENV_PATH — шлях до .env файлу
ENV_PATH = BASE_DIR / ".env"

# ============================================================================
# ЗАВАНТАЖЕННЯ ЗМІННИХ СЕРЕДОВИЩА
# ============================================================================
# load_dotenv читає файл .env і завантажує змінні в os.environ
load_dotenv(dotenv_path=ENV_PATH)

# BOT_TOKEN — токен від BotFather
# Читаємо його із .env; якщо не знайдений — буде None
# (перевірка відбуватиметься пізніше в main.py)
BOT_TOKEN = os.getenv("BOT_TOKEN")

# ============================================================================
# НАЛАШТУВАННЯ ЛОГУВАННЯ
# ============================================================================
# Формат логів: час [РІВЕНЬ] повідомлення
# Наприклад: 2026-07-13 11:15:58,123 [INFO] Start polling
LOGGING_FORMAT = "%(asctime)s [%(levelname)s] %(message)s"

# Рівень логування: INFO для звичайної роботи, DEBUG для деталей
LOGGING_LEVEL = logging.INFO

# Налаштування логування (використовується в main.py)
def setup_logging() -> None:
    """Налаштовує глобальне логування для всього бота."""
    logging.basicConfig(
        level=LOGGING_LEVEL,
        format=LOGGING_FORMAT,
    )


# ============================================================================
# ПАРАМЕТРИ ФОНОВОГО ЦИКЛУ
# ============================================================================
# DEBUG_MODE: True — інтервал повторення рахується в ХВИЛИНАХ. False — у ДНЯХ.
DEBUG_MODE = False  # Змініть на False для продакшну

# Як часто фоновий цикл перевіряє БД.
# Для дебагу ставимо 5 секунд, для звичайної роботи — 30-60 секунд.
REMINDER_CHECK_INTERVAL = 5 if DEBUG_MODE else 30

# ============================================================================
# ПАРАМЕТРИ БД
# ============================================================================
# Максимальна кількість пропущених інтервалів, які можуть бути "доганяні" за один раз
# (поки не використовується, але готово для майбутніх удосконалень)
MAX_SKIPPED_INTERVALS = 100
